#!/usr/bin/env python3
"""regen_burn_down.py -- ARC 14 step 3.  Regenerate THE_BURN_DOWN.md's LIVE accounting from the
lead register in THE_LIVE_ARC.md.

THE_BURN_DOWN's own description says it is "THE_LIVE_ARC's ledger, not a second register" -- and
it was hand-written at c54.27/c54.28 and never regenerated, so at c54.108 it was reporting
88 leads / 19 struck / 74 open against an actual 155 / 141 / 14.  Eighty revisions behind, and
the numbers it reported were the ones a node would use to decide what to work.

The historical sections (the c54.27 baseline, the first burn, the rules) are RECORD and are
preserved verbatim below the generated block: they are the argument that produced the gate, and
deleting them would throw away the reason the accounting exists.  Only the live accounting is
regenerated.

    python3 scripts/regen_burn_down.py            # refresh the generated block
    python3 scripts/regen_burn_down.py --check    # exit 1 if the block is missing or behind

Written r2377.  Stated for reversal.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
ARC = os.path.join(ROOT, 'THE_LIVE_ARC.md')
BURN = os.path.join(ROOT, 'THE_BURN_DOWN.md')

BEGIN = '<!-- BURN-DOWN LIVE BEGIN -- generated by scripts/regen_burn_down.py; do not hand-edit -->'
END = '<!-- BURN-DOWN LIVE END -->'
STATE_WORDS = ('DARYL', 'HOT', 'PART', 'OPEN', 'GATED')


def read_register():
    live, struck, retired = [], [], []
    for line in open(ARC, encoding='utf-8', errors='replace').read().split('\n'):
        m = re.match(r'^\| ~~(L-\d+)~~ \|', line)
        if m:
            struck.append(m.group(1)); continue
        m = re.match(r'^\| \*\*(L-\d+)\*\* \|(.*)$', line)
        if not m:
            continue
        lead, rest = m.group(1), m.group(2)
        cells = [c.strip().rstrip('|').strip() for c in rest.split(' | ')]
        st = ''
        cell = cells[3] if len(cells) > 3 else ''
        for w in STATE_WORDS:
            if re.search(r'\b' + w + r'\b', cell.upper()):
                st = w; break
        kind = 'WORK' if 'KIND:WORK' in cell.upper() else 'QUESTION'
        live.append((lead, st, cells[1] if len(cells) > 1 else '', kind))
    m = re.search(r'RETIRED IDS.*', open(ARC, encoding='utf-8', errors='replace').read())
    return live, struck, retired


def front():
    rs = [int(x) for x in re.findall(r'c54\.(\d+)',
          open(ARC, encoding='utf-8', errors='replace').read())]
    return max(rs) if rs else 0


def render(live, struck):
    total = len(live) + len(struck)
    frac = 100.0 * len(struck) / max(1, len(struck) + len([r for r in live if r[3] == 'QUESTION']))
    ques = [r for r in live if r[3] == 'QUESTION']
    work = [r for r in live if r[3] == 'WORK']
    by_state = {}
    for _, st, _, _ in ques:
        by_state[st or '—'] = by_state.get(st or '—', 0) + 1
    by_origin = {}
    for _, _, origin, _ in ques:
        key = 'folded from OPEN_PROBLEMS_MAP' if 'OPEN_PROBLEMS_MAP' in origin else 'this fork'
        by_origin[key] = by_origin.get(key, 0) + 1

    o = [BEGIN, '']
    o.append(f'## ⌗⌗ THE LIVE ACCOUNTING — generated at fork front c54.{front()}')
    o.append('')
    o.append('*Generated by `scripts/regen_burn_down.py` from the register in `THE_LIVE_ARC.md`. '
             '**Do not hand-edit this block.** Everything below the END marker is RECORD — the '
             'c54.27/c54.28 argument that produced `check_burndown` — and is kept verbatim.*')
    o.append('')
    o.append('> **⚠ WHY THIS BLOCK EXISTS (r2377).** *This file was written by hand at c54.27–c54.28 '
             'and never regenerated. At c54.108 it was still reporting **88 leads, 19 struck, 74 '
             'open, 20 HOT** against an actual **155 / 141 / 14 / 0** — eighty revisions behind, and '
             'those were the numbers a node would have used to decide what to work. **A ledger that '
             'is not generated is a ledger that will be wrong**, which is `ARC 14`\'s whole thesis.*')
    o.append('')
    o.append('| | at c54.27 *(the baseline below)* | **now** |')
    o.append('|---|---|---|')
    o.append(f'| registered | 88 | **{total}** |')
    o.append(f'| struck | 13 | **{len(struck)}** |')
    o.append(f'| open QUESTIONS | 75 | **{len(ques)}** |')
    o.append(f'| open WORK rows *(arcs and phases, folded r2378)* | — | **{len(work)}** |')
    o.append(f'| `HOT` | 49 *(60% of open)* | **{by_state.get("HOT", 0)}** '
             f'*({100.0 * by_state.get("HOT", 0) / len(ques):.0f}% of open questions)* |'
             if ques else '| `HOT` | 49 | **0** |')
    o.append(f'| struck fraction | 14.0% | **{frac:.1f}%** |')
    o.append('')
    o.append('**Open leads by state**')
    o.append('')
    o.append('| state | count |')
    o.append('|---|---|')
    for st in ('DARYL', 'HOT', 'PART', 'OPEN', 'GATED', '—'):
        if st in by_state:
            o.append(f'| `{st}` | {by_state[st]} |')
    o.append('')
    o.append('**Open leads by origin**')
    o.append('')
    o.append('| origin | count |')
    o.append('|---|---|')
    for k, v in sorted(by_origin.items()):
        o.append(f'| {k} | {v} |')
    o.append('')
    o.append('> **⌗ THE COUNTS ARE PER KIND (r2379).** *`kind:QUESTION` rows are things to answer and '
             'carry the burn-down; `kind:WORK` rows are programmes with steps whose freshness is gated '
             'by `corpus/check_arcs.py`. **The struck fraction is scoped to questions so it cannot '
             'quietly start measuring something else.***')
    o.append('')
    o.append('**The open register, in ID order** — *the working list is '
             '[`WHATS_TEED_UP.md`](WHATS_TEED_UP.md), also generated.*')
    o.append('')
    o.append('| lead | state |')
    o.append('|---|---|')
    for lead, st, _, k in sorted(live, key=lambda r: (r[3], int(r[0][2:]))):
        o.append(f'| **`{lead}`** | {k} · {st or "—"} |')
    o.append('')
    o.append('*⌗ The gate that enforces the budget is `corpus/check_burndown.py`; the ID-space '
             'integrity check lives there too.*')
    o.append('')
    o.append('---')
    o.append('')
    o.append('# ⌫ BELOW HERE IS RECORD — the c54.27–c54.28 argument, kept verbatim')
    o.append('')
    o.append(END)
    return '\n'.join(o)


def main():
    live, struck, _ = read_register()
    block = render(live, struck)
    t = open(BURN, encoding='utf-8', errors='replace').read()
    if '--check' in sys.argv:
        if BEGIN not in t:
            print('  [FAIL] THE_BURN_DOWN carries no generated block'); return 1
        cur = t.split(BEGIN)[1].split(END)[0]
        want = f'| open QUESTIONS | 75 | **{len([r for r in live if r[3] == "QUESTION"])}** |'
        if want not in cur:
            print(f'  [FAIL] burn-down block is behind the register '
                  f'({len([r for r in live if r[3] == "QUESTION"])} questions, '
                  f'{len([r for r in live if r[3] == "WORK"])} work, {len(struck)} struck)')
            return 1
        print(f'  burn-down current: {len([r for r in live if r[3] == "QUESTION"])} questions + '
              f'{len([r for r in live if r[3] == "WORK"])} work, {len(struck)} struck')
        return 0
    if BEGIN in t:
        pre, rest = t.split(BEGIN, 1)
        post = rest.split(END, 1)[1] if END in rest else ''
        t = pre + block + post
    else:
        # insert after frontmatter + title block, before the first '---' separator
        marker = '\n---\n'
        head_end = t.index(marker, t.index('# THE BURN-DOWN')) + len(marker)
        t = t[:head_end] + '\n' + block + '\n' + t[head_end:]
    # keep the frontmatter description honest
    t = re.sub(r'^name: the-burn-down$',
               f'name: the-burn-down\nkind: VIEW\ncurrent: c54.{front()}', t, count=1, flags=re.M)
    t = re.sub(r'^kind: VIEW\ncurrent: c54\.\d+\nkind: VIEW\ncurrent: c54\.\d+$',
               f'kind: VIEW\ncurrent: c54.{front()}', t, count=1, flags=re.M)
    t = re.sub(r'^current: c54\.\d+$', f'current: c54.{front()}', t, count=1, flags=re.M)
    t = re.sub(r'^description: .*$',
               'description: The register\'s accounting — generated from THE_LIVE_ARC by '
               'scripts/regen_burn_down.py. The live block is generated; below it is the '
               'c54.27–c54.28 record that produced check_burndown.',
               t, count=1, flags=re.M)
    open(BURN, 'w', encoding='utf-8').write(t)
    print(f'  wrote THE_BURN_DOWN live block: {len(live)} open, {len(struck)} struck, '
          f'front c54.{front()}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
