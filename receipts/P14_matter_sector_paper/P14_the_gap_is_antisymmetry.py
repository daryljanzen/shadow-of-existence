def mul(g, h):
    (gs, gd), (hs, hd) = g, h
    s = tuple(gs[hs[i]] for i in range(3))
    d = tuple((hd[i] + gd[hs[i]]) % 3 for i in range(3))
    return (s, d)


def sgn(s):
    return 1 if list(s) in ([0, 1, 2], [1, 2, 0], [2, 0, 1]) else -1


def det(g):
    s, d = g
    return sgn(s) * W(sum(d))


def trace(g):
    s, d = g
    return sp.simplify(sp.expand_complex(sum((W(d[i]) for i in range(3) if s[i] == i),
                                             sp.Integer(0))))


def mat(g):
    s, d = g
    M = sp.zeros(3, 3)
    for i in range(3):
        M[s[i], i] = W(d[i])
    return M


def close(gens):
    ident = ((0, 1, 2), (0, 0, 0))
    G, frontier = {ident}, [ident]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = mul(x, g)
            if y not in G:
                G.add(y)
                frontier.append(y)
    return sorted(G)


