    Pr = sp.simplify(sp.expand_complex(Pr / len(G)))
    assert sp.simplify(sp.expand_complex(Pr * Pr - Pr)) == sp.zeros(dim, dim), \
        "the average over a GROUP must be idempotent"
    return Pr.columnspace()


