def classify(terms):
    idxs = [ijk for _, ijk in terms]
    if all(len(set(x)) == 1 for x in idxs):
        return "sum_m e_m (x) e_m (x) e_m   -- ALL THREE CONSTITUENTS ON ONE VANTAGE"
    if all(len(set(x)) == 3 for x in idxs):
        par = {sgn(x) for x in idxs}
        if len(idxs) == 6 and par == {1, -1}:
            cs = {tuple(x): c for c, x in terms}
            anti = all(sp.simplify(cs[x] - sgn(x) * cs[(0, 1, 2)]) == 0 for x in cs)
            return ("epsilon_abc  ** THE BARYON **" if anti
                    else "one-per-vantage, both parities, NOT antisymmetric")
        return ("one-per-vantage, EVEN permutations only (cyclic)" if par == {1}
                else "one-per-vantage, ODD permutations only (cyclic)")
    return "mixed"


