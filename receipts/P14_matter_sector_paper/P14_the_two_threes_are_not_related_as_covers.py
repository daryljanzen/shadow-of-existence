worst = 0.0
n_checked = 0
for M2 in MS:
    for r in np.roots([1.0, 0.0, -ALPHA ** 2, 2 * (M2 / 2) * ALPHA ** 2]):
        for w in (W, W ** 2):
            val = abs(cubic(w * r, M2 / 2))
            pred = abs(r * (1 - w))
            worst = max(worst, abs(val - pred))
            n_checked += 1
            # ** the identity is EXACT, so the check is that the residual EQUALS |r(1-w)| and not
            # merely that it is non-zero.  A test that only asked "is it non-zero" would pass on a
            # wrong formula. **
