fail = []

W = np.exp(2j * np.pi / 3)                       # a primitive cube root of unity
ALPHA = 1.0                                      # the gauge the computation is done in


def cubic(r, M):
    """r^3 - alpha^2 r + 2 M alpha^2, at alpha = 1"""
    return r ** 3 - ALPHA ** 2 * r + 2 * M * ALPHA ** 2


