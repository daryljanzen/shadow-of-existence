"""LAP-K — the direction that orders the cosmic layer is a Killing field, and its norm is -f.

THE CLAIM.  In the proper-frame chart of the E=1 comoving congruence,
    ds^2 = -dtau^2 + R'(tt)^2 dchi^2 + R(tt)^2 dOmega^2,   tt = tau + chi,
the metric depends on (tau, chi) only through tt, so K = d_chi - d_tau is a Killing field.  K lies in
every layer tt = const (dtt(K) = 0) and is the direction along which the layer's comoving worldlines
(constant chi) are ordered.  Its norm is |K|^2 = R'^2 - 1, and on the lap's law (dR/dtt)^2 = 1 - f,
    |K|^2 = -f(r),      (dr/dtt)^2 = 1 + |K|^2,      d^2r/dtt^2 = (1/2) d|K|^2/dr.
So the rate and acceleration the F-triptych plots are the norm of the layer's ordering direction.

AT THE SEAMS (f = 0) K is null and the layer is a null hypersurface generated by K: P1's metric
singularity -- the comoving worldlines threaded in order by one generator, sharing the areal radius,
metrically coincident.  Future-directed along the generator, proper time on the worldlines it meets
increases and chi decreases, so the generator's order is at once the order across worldlines and the
order in their proper times.  nabla_K K = kappa K with kappa = |f'|/2: 3 sqrt3/4 alpha at the back seam
(simple root; Killing parameter exponentially related to affine), 0 at the front seam (the Nariai
double root, where P7's Null-Boundary Correspondence is the identity; Killing parameter IS affine).

LOCI on the Nariai member (alpha = 1):  back seam |K|^2 = 0;  turnaround |K|^2 = -1 (K unit timelike:
Killing time is proper time -- the rest-frame locus of P15);  Euclidean null |K|^2 = -2;  branch point
|K|^2 -> -inf / +inf (time turned to space through infinite norm);  front seam |K|^2 = 0;  then > 0.
Companion: LAP_complete_account.py (the same loci as values of f).
"""
import sympy as sp

tau, chi, th, ph = sp.symbols('tau chi theta phi', real=True)
tt = sp.Symbol('tt', real=True)
Rf = sp.Function('R')
X = (tau, chi, th, ph)
R = Rf(tau + chi)
g = sp.diag(-1, sp.diff(R, chi)**2, R**2, R**2*sp.sin(th)**2)   # R' = dR/dtt = dR/dchi
K = sp.Matrix([-1, 1, 0, 0])

# 1. Killing: K has constant components, so L_K g = K^c d_c g_ab; g depends on tau,chi only via tau+chi
LKg = sp.zeros(4)
for a in range(4):
    for b in range(4):
        LKg[a, b] = sum(K[c]*sp.diff(g[a, b], X[c]) for c in range(4))
assert sp.simplify(LKg) == sp.zeros(4), 'K must be Killing'
# control: d_chi alone is not Killing
Lchi = sp.simplify(sp.diff(g, chi)); assert Lchi != sp.zeros(4), 'control: d_chi is not Killing'

# 2. K tangent to the layer and its norm
assert (sp.Matrix([[1, 1, 0, 0]])*K)[0] == 0, 'dtt(K) = 0'
K2 = sp.simplify((K.T*g*K)[0])
Rp = sp.Symbol('Rp')
assert sp.simplify(K2.subs(sp.diff(R, chi), Rp) - (Rp**2 - 1)) == 0
print('|K|^2 =', K2)

# 3. On the lap's law: rate^2 = 1 - f, so |K|^2 = -f, rate^2 = 1 + |K|^2, acceleration = half the gradient
M, a = sp.symbols('M alpha', positive=True); r = sp.Symbol('r')
f = 1 - 2*M/r - r**2/a**2
A = (2*M*a**2)**sp.Rational(1, 3)
law = A*sp.sinh(sp.Rational(3, 2)*tt/a)**sp.Rational(2, 3)
rate2 = sp.diff(law, tt)**2
import mpmath as mp; mp.mp.dps = 40
for Mv, av, tv in [(0.19245, 1.0, 0.7), (0.05, 2.0, 1.3), (1.1, 0.6, 0.25), (0.3, 1.7, 3.0)]:
    sub = {M: sp.Rational(str(Mv)), a: sp.Rational(str(av)), tt: sp.Rational(str(tv))}
    lhs = sp.N(rate2.subs(sub), 30); rhs = sp.N((1 - f).subs(r, law).subs(sub), 30)
    assert abs(lhs - rhs) < 1e-25, ('rate law', Mv, av, tv)
    acc = sp.N(sp.diff(law, tt, 2).subs(sub), 30); half_grad = sp.N((sp.diff(-f, r)/2).subs(r, law).subs(sub), 30)
    assert abs(acc - half_grad) < 1e-25, ('acceleration = (1/2) d|K|^2/dr', Mv, av, tv)
print('rate^2 = 1 - f = 1 + |K|^2 and d2r/dtt2 = (1/2) d|K|^2/dr: verified at 4 (M, alpha, tt) points to 1e-25')

# 4. nabla_K K on the layer.  Write g_chichi = P(tt) (= R'^2) and g_thth = Q(tt) (= R^2) as generic
#    functions of tt = tau+chi; the metric is diagonal, so its inverse is 1/g_ii.
Pf, Qf = sp.Function('P'), sp.Function('Q'); s_ = tau + chi
G = sp.diag(-1, Pf(s_), Qf(s_), Qf(s_)*sp.sin(th)**2)
Ginv = sp.diag(*[1/G[i, i] for i in range(4)])
def Gam(i, j, k):
    return sp.simplify(sum(Ginv[i, l]*(sp.diff(G[l, j], X[k]) + sp.diff(G[l, k], X[j]) - sp.diff(G[j, k], X[l]))/2 for l in range(4)))
accK = sp.Matrix([sp.simplify(sum(Gam(i, j, k)*K[j]*K[k] for j in range(4) for k in range(4))) for i in range(4)])
P0, P1 = sp.symbols('P0 P1')            # P and its derivative dP/dtt
accK = accK.subs(sp.Derivative(Pf(s_), chi), P1).subs(sp.Derivative(Pf(s_), tau), P1)
accK = sp.simplify(accK.replace(lambda e: isinstance(e, sp.Subs), lambda e: P1).subs(Pf(s_), P0))
print('nabla_K K (P = R\'^2, P1 = dP/dtt) =', list(accK))
# on a seam layer P0 = R'^2 = 1 and P1 = 2 R' R'' = 2 R'': nabla_K K = kappa K
Rpp = sp.Symbol('Rpp')
accSeam = accK.subs({P0: 1, P1: 2*Rpp})
kap = sp.simplify(accSeam[1]/K[1]); assert sp.simplify(accSeam - kap*K) == sp.zeros(4, 1)
print('on a seam layer: nabla_K K = kappa K with kappa =', kap)
fN = f.subs({M: 1/(3*sp.sqrt(3)), a: 1})
kback = sp.simplify(kap.subs(Rpp, (-sp.diff(fN, r)/2).subs(r, -2/sp.sqrt(3))))
kfront = sp.simplify(kap.subs(Rpp, (-sp.diff(fN, r)/2).subs(r, 1/sp.sqrt(3))))
assert sp.simplify(sp.Abs(kback) - 3*sp.sqrt(3)/4) == 0 and kfront == 0
print('kappa: back seam', kback, '(|kappa| = 3 sqrt3/4 = surface gravity), front seam', kfront)

# 5. the seam layer is null and K is null on it; future-directed -K raises proper time, lowers chi
ind = sp.diag(sp.diff(R, chi)**2 - 1, R**2, R**2*sp.sin(th)**2).subs(sp.diff(R, chi), 1)   # tau = tt_s - chi on the layer
assert ind.det() == 0, 'seam layer degenerate -> null hypersurface'
assert sp.simplify(K2.subs(sp.diff(R, chi), 1)) == 0
U = sp.Matrix([1, 0, 0, 0])                                # comoving 4-velocity, future-directed
assert (U.T*g*(-K))[0] == -1, '-K future-directed (g(U,-K) < 0)'
print('seam layer null; K null on it; future along the generator: dtau/dl = +1, dchi/dl = -1')

# 6. the lap's loci on the Nariai member
vals = {'back seam': -2/sp.sqrt(3), 'turnaround': -(2/(3*sp.sqrt(3)))**sp.Rational(1, 3), 'front seam': 1/sp.sqrt(3)}
expect = {'back seam': 0, 'turnaround': -1, 'front seam': 0}
for k, v in vals.items():
    K2v = sp.nsimplify(sp.simplify(-fN.subs(r, v))); assert K2v == expect[k], (k, K2v)
    print(f'  {k:11s} r = {sp.N(v, 8)}   |K|^2 = {K2v}')
rE = sp.nsolve(fN - 2, r, -0.34); assert abs(rE + 0.344142) < 1e-6
print(f'  Euclidean null r = {float(rE):.6f}   |K|^2 = -2')
assert sp.limit(-fN, r, 0, '-') == -sp.oo and sp.limit(-fN, r, 0, '+') == sp.oo
print('  branch point: |K|^2 -> -oo from r<0, +oo from r>0')
print('LAP-K: all assertions hold')
