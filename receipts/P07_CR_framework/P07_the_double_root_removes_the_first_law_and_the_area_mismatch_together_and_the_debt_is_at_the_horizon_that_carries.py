print(__doc__)

r, M, al, lP, Lam = sp.symbols('r M alpha ell_P Lambda', positive=True)
f = 1 - 2 * M / r - r ** 2 / al ** 2
M_N, r_N = sp.sqrt(3) * al / 9, al / sp.sqrt(3)

# =========================================================================================
print("=" * 94)
print("PART 1 (C1) — THE THREE COINCIDENCES ARE ONE IDENTITY, AND IT IS DERIVED NOT QUOTED")
print("=" * 94)
V = sp.simplify(f / r ** 2)
photon = sp.solve(sp.Eq(sp.diff(V, r), 0), r)
print(f"""
    null circular orbit: d/dr (f/r^2) = 0  ->  r = {photon}
      and the radius carries no alpha: {all(al not in sp.simplify(x).free_symbols for x in photon)}
    Nariai:  3M = {sp.simplify(3 * M_N)},  r_h = {sp.simplify(r_N)}
""")
check("the SdS photon sphere sits at r = 3M exactly, and independently of alpha — which is why it can meet a "
      "horizon whose radius is all alpha",
      photon == [3 * M] and all(al not in sp.simplify(x).free_symbols for x in photon))
check("⚑ at the Nariai mass 3M = r_h exactly, so the photon sphere sits ON the horizon",
      sp.simplify(3 * M_N - r_N) == 0)
check("f vanishes there twice over — at the horizon and at the photon sphere, being the same radius",
      sp.simplify(f.subs({r: r_N, M: M_N})) == 0
      and sp.simplify(f.subs({r: 3 * M_N, M: M_N})) == 0)
rp = sp.Symbol('r_p', positive=True)
lam2 = f.subs(r, rp) * (2 * f.subs(r, rp) - rp ** 2 * sp.diff(f, r, 2).subs(r, rp)) / (2 * rp ** 2)
print(f"    the circular null orbit's Lyapunov exponent squared at Nariai: "
      f"{sp.simplify(lam2.subs({rp: r_N, M: M_N}))}")
check("⚑ and the Lyapunov exponent vanishes there, being proportional to f(r_photon) which is f(r_h) = 0 — so "
      "all three coincidences are the single identity 3M = r_h",
      sp.simplify(lam2.subs({rp: r_N, M: M_N})) == 0)
check("and the surface gravity vanishes with them, f' also being zero at the double root",
      sp.simplify(sp.diff(f, r).subs({r: r_N, M: M_N})) == 0)

