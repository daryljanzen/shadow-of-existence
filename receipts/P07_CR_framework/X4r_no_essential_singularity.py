_fail4 = []

# r^3 = 2 M alpha^2 sinh^2(3 tau / 2 alpha) -- the bead law, cubed to keep it polynomial in r
_S = _sp.sinh(3 * _tau / (2 * _al))
_r3 = 2 * _M * _al**2 * _S**2
print("  r(tau)^3 = 2 M alpha^2 sinh^2(3 tau / 2 alpha)")

# (i) the CUBE is entire: sinh is entire, so r^3 is entire, so r^3 has NO singularity at all --
#     finite or essential.  Every singular point of r is therefore a BRANCH point of the cube
#     root, and a cube root has only algebraic branch points.
_z = _sp.Symbol('zeta')
_ser = _sp.series(_r3.subs(_tau, _z), _z, 0, 8).removeO()
print(f"  its Taylor series about tau = 0 begins {_sp.simplify(_ser)}")
if _ser.has(1 / _z) or _ser.has(_sp.log(_z)):
    _fail4.append("r^3 is not entire at tau = 0")

# (ii) the zeros of sinh(3 tau / 2 alpha) are tau_k = 2 pi i alpha k / 3, all SIMPLE, so sinh^2
#      -- and with it r^3 -- has a DOUBLE zero there, and r ~ (tau - tau_k)^(2/3): an algebraic
#      branch point of order three.  ** The first draft of this check asserted a SIMPLE zero of
#      r^3 and fired; sinh is squared in the bead law, which is exactly why the exponent is 2/3
#      and not 1/3.  Recorded because the assertion is what caught it. **
_w = _sp.Symbol('w')
# sinh(3(tau_k + w)/2alpha) = sinh(i pi k + 3w/2alpha) = (-1)^k sinh(3w/2alpha), so the SQUARE is
# the same function of w at every k.  Verified as an identity rather than assumed, then expanded.
print(f"\n  {'k':>3} {'tau_k':>22} {'shift identity holds':>22}")
for _k in (1, 2, 3):
    _tk = 2 * _sp.pi * _sp.I * _al * _k / 3
    _id = _sp.simplify(_sp.expand(_sp.expand_trig(
        _sp.sinh(3 * (_tk + _w) / (2 * _al))**2 - _sp.sinh(3 * _w / (2 * _al))**2)))
    print(f"  {_k:>3} {str(_tk):>22} {str(_id == 0):>22}")
    if _id != 0:
        _fail4.append(f"the shift identity fails at k={_k}: {_id}")
_shift = 2 * _M * _al**2 * _sp.sinh(3 * _w / (2 * _al))**2
_ser_k = _sp.expand(_sp.series(_shift, _w, 0, 6).removeO())
_pol = _sp.Poly(_ser_k, _w)
_ord = min(m[0] for m in _pol.monoms())
_lead_k = _sp.simplify(_pol.coeff_monomial(_w**_ord))
print(f"\n  r^3(tau_k + w) = {_sp.simplify(_ser_k)} + O(w^6)")
