import sympy as _sp

_tau, _eps = _sp.symbols('tau epsilon', positive=True)
_al = _sp.Symbol('alpha', positive=True)
_M = _sp.Symbol('M', positive=True)
print()
print("=" * 78)
print("THE BEAD RADIUS: ALGEBRAIC BRANCH POINTS, AND NOTHING ELSE")
