def flat(t):
    return re.sub(r'\s+', ' ', t)


def locate(lit, target, receipt):
    """the target file and the PHYSICAL LINE the literal sits on, AS OF `BEFORE` -- the longest
    leading chunk of the literal that fits on one line, so a wrapped paper sentence resolves to its
    first line and a two-word prefix can never match a different passage"""
    if target == 'PAPER':
        cands = _TEX
    else:
        cands = [f.split(':', 1)[1] for f in
                 _git('grep', '-l', '-F', '-e', lit, BEFORE, '--').split('\n') if ':' in f]
        if not cands:
            cands = [f.split(':', 1)[1] for f in
                     _git('grep', '-l', '-F', '-e', ' '.join(lit.split()[:6]), BEFORE,
                          '--').split('\n') if ':' in f]
        cands = [f for f in cands if f != receipt]
    for rel in cands:
        txt = at_before(rel)
        if lit not in txt and flat(lit) not in flat(txt):
            continue
        _lines = txt.split('\n')
        _w = lit.split()
        for _take in range(len(_w), 1, -1):
            _chunk = ' '.join(_w[:_take])
            _hit = [_n for _n, _l in enumerate(_lines, 1) if _chunk in _l]
            if _hit:
                return rel, _hit[0]
    return None, None


