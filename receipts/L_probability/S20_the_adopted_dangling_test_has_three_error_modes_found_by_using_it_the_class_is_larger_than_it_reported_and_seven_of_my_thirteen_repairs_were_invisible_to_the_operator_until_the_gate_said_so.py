def _folded(node):
    """the text of a string expression -- a constant, an implicit or explicit concatenation, or the
    literal parts of an f-string -- or None when the node is not one."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        a, b = _folded(node.left), _folded(node.right)
        return None if a is None or b is None else a + b
    return None


def literals_of(src):
    """every folded string literal in the file, and every one that stands to the LEFT of an `in`."""
    tree = ast.parse(src)
    names = {}
    for n in ast.walk(tree):
        if isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name):
            t = _folded(n.value)
            if t is not None:
                names[n.targets[0].id] = t
    allv, keyed = set(), set()
    for n in ast.walk(tree):
        t = _folded(n)
        if t is not None:
            allv.add(t)
    for n in ast.walk(tree):
        if isinstance(n, ast.Compare) and any(isinstance(o, ast.In) for o in n.ops):
            left = n.left
            t = _folded(left)
            if t is None and isinstance(left, ast.Name):
                t = names.get(left.id)
            if t is not None:
                keyed.add(t)
    return allv, keyed


