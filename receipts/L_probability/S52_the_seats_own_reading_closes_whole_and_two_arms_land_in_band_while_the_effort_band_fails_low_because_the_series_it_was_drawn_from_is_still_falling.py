def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _same(s):
    """the normalisation the repairs applied: emphasis unwrapped, LaTeX spacing and regex escaping
    removed, case folded -- so a span merely NORMALISED counts as carried and only a claim with no
    pinned text at all counts as invisible."""
    s = re.sub(r'\\(?:emph|textit|textbf)\{([^{}]*)\}', r'\1', s)
    s = re.sub(r'\\[;,!:>]', '', s)
    s = s.replace('\\$', '$').replace('\\{', '{').replace('\\}', '}').replace('\\\\', '\\')
    return re.sub(r'\s+', ' ', s).lower()


