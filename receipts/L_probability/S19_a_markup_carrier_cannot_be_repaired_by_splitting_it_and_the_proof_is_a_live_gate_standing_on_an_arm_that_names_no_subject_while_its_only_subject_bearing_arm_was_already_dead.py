_EMPH = re.compile(r'\\(?:emph|textit|textbf|textsl|textup|textsc)\{([^{}]*)\}')


def unemph(t, rounds=4):
    for _ in range(rounds):
        t2 = _EMPH.sub(r'\1', t)
        if t2 == t:
            break
        t = t2
    return t


def shape(rel):
    """a receipt's CODE FACTS by parsing -- module-level names and gate/check call count.  Parsed
    rather than quoted: three of `S18`'s gates were themselves quote pins at `r7256`, and the
    remedy was to read structure instead of text."""
    tree = ast.parse(open(os.path.join(ROOT, rel), encoding='utf-8').read())
    names, calls = set(), 0
    for n in ast.walk(tree):
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(n.name)
        elif isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store):
            names.add(n.id)
        elif isinstance(n, ast.Call) and isinstance(n.func, ast.Name) \
                and n.func.id in ('gate', 'check'):
            calls += 1
    return names, calls


