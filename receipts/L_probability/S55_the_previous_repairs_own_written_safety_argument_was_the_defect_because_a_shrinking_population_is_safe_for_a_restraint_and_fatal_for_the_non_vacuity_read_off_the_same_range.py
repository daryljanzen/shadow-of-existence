def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def one(prefix, where='receipts/L_probability'):
    hits = [x for x in git('ls-files', where).split('\n')
            if os.path.basename(x).startswith(prefix)]
    return hits[0] if hits else None


def mine_since(base, sess):
    """this seat's own commits since `base`, by the session marker on the commit body"""
    out = []
    for blk in git('log', '--no-merges', '--format=%H%x00%B%x01', 'HEAD',
                   '--not', base).split('\x01'):
        if '\x00' in blk:
            sha, body = blk.split('\x00', 1)
            m = re.search(r'^Claude-Session:\s*(\S+)', body, re.M)
            if m and m.group(1) == sess:
                out.append(sha.strip())
    return out


def intro_table(sha, filt, name_status):
    """the introducing commit of every path under `receipts/`, batched, one query"""
    args = ['log', f'--diff-filter={filt}', '--format=@@%h', sha, '--', 'receipts/']
    args.insert(3, '--name-status' if name_status else '--name-only')
    if name_status:
        args.insert(4, '-M')
    add, cur = {}, None
    for row in git(*args).split('\n'):
        if row.startswith('@@'):
            cur = row[2:]
        elif row.strip() and cur:
            f = row.split('\t')
            if name_status:
                if f[0].startswith('R') and len(f) >= 3:
                    add[f[2].strip()] = cur
                elif f[0].startswith('A') and len(f) >= 2:
                    add[f[1].strip()] = cur
            else:
                add[row.strip()] = cur
    return add


